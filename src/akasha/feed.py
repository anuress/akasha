ALLOWED_SUFFIXES = (".csv", ".xlsx")

# Directories akasha owns inside `files/`: a repo of that name would put a dataset where
# the lock files and the trash live.
RESERVED_REPOS = frozenset({".locks", ".trash"})

# `msvcrt.locking` reports contention as EACCES, and a lock it would deadlock on as EDEADLK.
LOCK_CONTENTION_ERRNOS = frozenset({errno.EACCES, errno.EDEADLK})
LOCK_RETRY_SECONDS = 0.1

# Names frontmatter would read back as a literal instead of as the name it is.
LITERAL_NAMES = frozenset({"null", "true", "false"})

# Above this the feed still happens: the warning says what it will cost.
LARGE_FILE_BYTES = 50 * 1024 * 1024

# A change-log line names what moved, never a cell value, so the log stays readable.
CHANGE_LINE_CAP = 50

CHANGE_LOG = "## Change log"

# The heading line, not that text anywhere: a field may itself be named `## Change log`.
CHANGE_LOG_LINE = re.compile(r"^## Change log$", re.MULTILINE)


class DatasetReadOnly(ValueError):
    """A dataset document is generated by `feed`, so an edit to it is thrown away on the
    next import. The knowledge write paths refuse it."""


# Datasets whose attach failed in the current run, as (dataset, reason). A module list
# keeps `index_path`'s return signature unchanged; `index_all` moves it into the stats the
# caller prints.
ATTACH_ERRORS: list[tuple[str, str]] = []


def _scrub(value: str) -> str:
    cleaned, _hits = redact(value)
    cleaned, _injections = scrub_injection(cleaned)
    return cleaned


def redact_units(units: list[Unit], cfg: Config) -> tuple[list[Unit], int]:
    """Scrub every stored string of a unit: each cell, the key and the label.

    The label is built from cells (excluded columns included) and both it and the key are
    stored and shown in a search result, so scrubbing only `fields` would leak through
    them. The count is the number of values that changed, which is what tells `feed add`
    how much it scrubbed.
    """
    if not cfg.scan_secrets:
        return units, 0
    changed = 0
    cleaned: list[Unit] = []
    for unit in units:
        key = _scrub(unit.key) if unit.key is not None else None
        label = _scrub(unit.label)
        fields = {name: _scrub(value) for name, value in unit.fields.items()}
        changed += ((key != unit.key) + (label != unit.label)
                    + sum(fields[name] != value for name, value in unit.fields.items()))
        if key != unit.key:
            # Distinct secret-shaped keys all redact to one placeholder, and a stored key
            # is what pairs a row across imports; a shared placeholder would pair
            # unrelated rows. Dropping it falls back to the locator.
            key = None
        cleaned.append(unit._replace(key=key, label=label, fields=fields))
    return cleaned, changed


def unit_state(file_sha: str, settings_sha: str, cfg: Config) -> str:
    """What the stored units are: the copy, its settings, and the scan policy of the run.

    The policy belongs in it because the same copy and settings must be split again once
    secret scanning is turned on, or units stored raw would look current forever.
    """
    policy = (
        cfg.scan_secrets,
        [(name, pattern.pattern) for name, pattern in SECRET_PATTERNS],
        [(name, pattern.pattern) for name, pattern in INJECTION_PATTERNS],
        sorted(INJECTION_STRIP_RULES),
    )
    digest = hashlib.sha256(json.dumps(policy).encode()).hexdigest()
    return f"{file_sha}:{settings_sha}:{digest[:12]}"


def _bad_settings(name: str, detail: str) -> str:
    return f"dataset '{name}': invalid settings: {detail}"


def _settings_from(meta: dict, name: str) -> FeedSettings:
    """The frontmatter carries the settings as real JSON when the file was written by
    `feed`; an older hand-written doc may carry the string form.

    Validated because frontmatter is data: handing it straight to `FeedSettings` raises
    `TypeError`, which would end the whole index run instead of one dataset.
    """
    raw = meta.get("settings")
    if isinstance(raw, str):
        try:
            raw = json.loads(raw)
        except json.JSONDecodeError:
            raise ValueError(_bad_settings(name, "not a JSON object")) from None
    if not isinstance(raw, dict):
        raise ValueError(_bad_settings(name, "not an object"))
    unknown = sorted(set(raw) - set(FeedSettings.__dataclass_fields__))
    if unknown:
        raise ValueError(_bad_settings(name, f"unknown key {', '.join(map(repr, unknown))}"))
    for key in ("key", "sheet", "label"):
        if raw.get(key) is not None and not isinstance(raw[key], str):
            raise ValueError(_bad_settings(name, f"{key} must be a string or null"))
    for key in ("require", "exclude"):
        value = raw.get(key, [])
        if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
            raise ValueError(_bad_settings(name, f"{key} must be a list of strings"))
    header_row = raw.get("header_row", 1)
    if isinstance(header_row, bool) or not isinstance(header_row, int) or header_row < 1:
        raise ValueError(_bad_settings(name, "header_row must be an integer >= 1"))
    return FeedSettings(**raw)


def _insert_chunks(conn: sqlite3.Connection, doc_id: str, name: str,
                   units: list[Unit]) -> int:
    row = conn.execute("SELECT title FROM documents WHERE id = ?", (doc_id,)).fetchone()
    title = row["title"] if row else ""
    start = conn.execute(
        "SELECT COALESCE(MAX(ord), -1) + 1 AS next FROM chunks WHERE document_id = ?",
        (doc_id,)).fetchone()["next"]
    count = 0
    for unit in units:
        for field, value in unit.fields.items():
            # The label is part of the id because it is part of the embedded text: a
            # relabelled cell must not keep the vector of its old label.
            chunk_id = feed_store.unit_chunk_id(name, unit.locator, field,
                                                f"{unit.label}\0{value}")
            # Delete before insert: a REPLACE conflict does not fire `chunks_ad`, so the
            # FTS row of the old text would survive the rowid being reused and the same
            # term would match a chunk that no longer holds it.
            conn.execute("DELETE FROM chunks WHERE id = ?", (chunk_id,))
            conn.execute(
                "INSERT INTO chunks (id, document_id, title, heading, body, ord)"
                " VALUES (?, ?, ?, ?, ?, ?)",
                (chunk_id, doc_id, title, f"{unit.locator} · {field}",
                 f"{unit.label} · {field}: {value}", start + count))
            conn.execute(
                "INSERT OR REPLACE INTO feed_chunks (chunk_id, dataset, locator, field)"
                " VALUES (?, ?, ?, ?)", (chunk_id, name, unit.locator, field))
            count += 1
    return count


def attach(conn: sqlite3.Connection, cfg: Config, doc_id: str, meta: dict, *,
           path: Path | None = None, settings: FeedSettings | None = None,
           units: list[Unit] | None = None) -> int:
    """Make one chunk per cell of the dataset, from `units` when the caller holds them.

    Returns the number of chunks written. Never commits and never raises for a data
    problem: the last good units are re-attached, so search keeps answering, and the
    reason is recorded for the caller to surface.
    """
    name = meta["dataset"]
    # The chunk rows themselves were already dropped by whoever replaced this document's
    # chunks; only the mapping that says which of them were a cell survives here.
    conn.execute("DELETE FROM feed_chunks WHERE dataset = ?", (name,))
    try:
        state = unit_state(meta["sha256"], meta["settings_sha256"], cfg)
        if units is None:
            stored = feed_store.load_units(conn, name)
            if feed_store.stored_state(conn, name) == state and stored:
                units = stored
            else:
                units, _redacted = redact_units(
                    splitters.split(path or Path(meta["file"]), name,
                                    settings or _settings_from(meta, name)).units, cfg)
                feed_store.replace_units(conn, name, units, state)
        return _insert_chunks(conn, doc_id, name, units)
    except (ValueError, OSError, KeyError) as exc:
        ATTACH_ERRORS.append((name, str(exc)))
        emit(conn, "feed.attach_failed", commit=False, dataset=name, error=str(exc))
        return _insert_chunks(conn, doc_id, name, feed_store.load_units(conn, name))


@dataclass
class FeedResult:
    """What one feed did: where the copy went, what it holds, and what changed."""

    name: str
    repo: str
    doc_id: str
    copy: Path
    units: int
    diff: Diff | None
    unchanged: bool
    renamed: list[tuple[str, str]]
    warnings: list[str]
    redacted: int


def _copy_path(cfg: Config, repo: str, name: str, suffix: str) -> Path:
    return cfg.knowledge_dir.parent / "files" / repo / f"{name}{suffix}"


def _staging_path(cfg: Config, repo: str, name: str, suffix: str) -> Path:
    """Staged beside the copy with a real extension, so the splitter dispatches on it."""
    return cfg.knowledge_dir.parent / "files" / repo / f"{name}.staging{suffix}"


def _trash_path(cfg: Config, repo: str, name: str, suffix: str) -> Path:
    """Where a copy goes when it leaves the dataset, under the repo it belonged to.

    Stamped with the moment it was trashed: the stamp orders two copies of one name, and
    `purge` ages a copy by it, since the file itself keeps the mtime of the export it was.
    The stamp has one-second resolution, so the counter keeps a second copy trashed inside
    that second from replacing the first.
    """
    base = f"{name}-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S')}"
    folder = cfg.knowledge_dir.parent / "files" / ".trash" / repo
    counter = 0
    while True:
        tail = f"-{counter}" if counter else ""
        # Both extensions share one counter, so the trash keeps the order of the moves.
        if all(not (folder / f"{base}{tail}{other}").exists()
               for other in ALLOWED_SUFFIXES):
            return folder / f"{base}{tail}{suffix}"
        counter += 1


def trashed_copies(cfg: Config, repo: str, name: str) -> list[Path]:
    """The trashed copies of one dataset, oldest first.

    The stamp in the name is what orders them, so the last one is the newest and is what a
    restore puts back; the counter breaks a tie inside one stamp.
    """
    folder = cfg.knowledge_dir.parent / "files" / ".trash" / repo
    root = folder.resolve()
    found: list[tuple[tuple[str, int], Path]] = []
    for suffix in ALLOWED_SUFFIXES:
        # Exactly its own stamp, not a prefix: `sales` must not match `sales-2024-<stamp>`.
        pattern = re.compile(re.escape(name) + r"-(\d{8}T\d{6})(?:-(\d+))?"
                             + re.escape(suffix))
        for path in folder.glob(f"{name}-*{suffix}"):
            match = pattern.fullmatch(path.name)
            # A symlink in the trash can point anywhere, and a restore that followed one
            # would copy a file from outside the trash into the dataset's copy path.
            if match is None or path.is_symlink() or not path.is_file():
                continue
            if not path.resolve().is_relative_to(root):
                continue
            found.append(((match.group(1), int(match.group(2) or 0)), path))
    return [path for _order, path in sorted(found, key=lambda item: item[0])]


def _dataset_doc_path(cfg: Config, repo: str, name: str) -> Path:
    """Where `feed` puts a dataset's document: its id derives from exactly this path."""
    return cfg.knowledge_dir / repo / "datasets" / f"{name}.md"


def _live_dataset_refusal(name: str, path: Path) -> ValueError:
    return ValueError(f"'{name}' is live at {path}; remove it before restoring this one")


def _lock(cfg: Config, name: str) -> IO[str]:
    """One feed of a name at a time.

    Two feeds of one name would trade the staging, backup and copy paths with each other
    before either reaches the database lock, so one caller's bytes could end up under the
    other caller's document. The lock file outlives the call; `flock` does not.
    """
    path = cfg.knowledge_dir.parent / "files" / ".locks" / f"{name}.lock"
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = path.open("a+")
    try:
        import fcntl
    except ImportError:                     # Windows
        import msvcrt
        handle.seek(0)
        # `LK_LOCK` gives up after about ten seconds where `flock` blocks until it has the
        # lock, so the retry is what makes both platforms wait instead of fail. Only
        # contention is worth waiting for; a bad handle has to fail at once.
        while True:
            try:
                msvcrt.locking(handle.fileno(), msvcrt.LK_LOCK, 1)
                break
            except OSError as failure:
                if failure.errno not in LOCK_CONTENTION_ERRNOS:
                    handle.close()
                    raise
                time.sleep(LOCK_RETRY_SECONDS)
    else:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
    return handle


def _unlock(handle: IO[str]) -> None:
    """Release a lock taken by `_lock`, through the mechanism that took it."""
    try:
        import fcntl
    except ImportError:                     # Windows
        import msvcrt
        handle.seek(0)
        msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
    else:
        fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
    handle.close()


def _dataset_doc(cfg: Config, name: str) -> Path | None:
    """The dataset document of a name, whichever repo folder holds it.

    The name is global, so an existing document under another repo is what makes a feed
    there a refusal rather than a second, silently diverging dataset.
    """
    for candidate in sorted(cfg.knowledge_dir.glob(f"*/datasets/{name}.md")):
        if candidate.is_file():
            return candidate
    return None


def _repo_name(cfg: Config, repo: str) -> str:
    """The repo names a directory under the knowledge dir, so it gets the same check as
    `knowledge.write`: a plain name, and a folder that stays inside the knowledge dir."""
    folder = cfg.knowledge_dir / repo
    if (not knowledge._REPO_NAME.fullmatch(repo) or repo in (".", "..")
            or repo.casefold() in RESERVED_REPOS
            or not folder.resolve().is_relative_to(cfg.knowledge_dir.resolve())):
        raise ValueError(
            f"invalid repo {repo!r}: use a plain name of letters, digits, '.', '_' and '-'")
    return repo


def _resolve_repo(cfg: Config, repo: str | None) -> str:
    if repo == "*":
        raise ValueError("invalid repo '*': a dataset belongs to one repo")
    if repo:
        return _repo_name(cfg, repo)
    derived, _source = gitctx.resolve_repo(cfg, Path.cwd(), None)
    return _repo_name(cfg, derived) if derived else "_global"


def _unit_line(unit: Unit) -> str:
    identity = f"key:{unit.key}" if unit.key is not None else unit.locator
    names = ", ".join(sorted(unit.fields))
    return f"- {identity} {unit.label}" + (f": {names}" if names else "")


def _change_line(change: Change) -> str:
    names = ", ".join(change.fields)
    return f"- {change.identity} {change.label}" + (f": {names}" if names else "")


def _change_section(units: int, changes: Diff | None) -> str:
    """One dated section: what the feed counted, then what moved.

    A line carries the identity and the label of a row plus the names of the fields that
    changed; a cell value would grow the log without bound and put into a document what
    redaction exists to keep out of one.
    """
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    lines = [f"### {stamp}"]
    if changes is None:
        lines.append(f"first feed: {units} units")
        return "\n".join(lines)
    lines.append(f"+{len(changes.added)} -{len(changes.removed)} ~{len(changes.changed)}")
    entries = ([_unit_line(unit) for unit in changes.added]
               + [_unit_line(unit) for unit in changes.removed]
               + [_change_line(change) for change in changes.changed])
    lines.extend(entries[:CHANGE_LINE_CAP])
    if len(entries) > CHANGE_LINE_CAP:
        lines.append(f"- … and {len(entries) - CHANGE_LINE_CAP} more")
    return "\n".join(lines)


def _earlier_sections(previous_text: str | None) -> str:
    """The change log of the document being replaced, carried below the new section.

    The body only, and by a heading line: a field called `## Change log` sits inside the
    fields list, and searching the whole text would carry the rest of the document along.
    """
    if not previous_text:
        return ""
    _meta, body = markdown.parse_frontmatter(previous_text)
    match = CHANGE_LOG_LINE.search(body)
    return body[match.end():].strip("\n") if match else ""


def _doc_body(name: str, original: str, units: list[Unit], headers: list[str],
              changes: Diff | None, previous_text: str | None) -> str:
    today = datetime.now(timezone.utc).date().isoformat()
    sections = [
        f"Fed from {original} on {today}: {len(units)} units, {len(headers)} fields.",
        "## Fields",
        "\n".join(f"- {header}" for header in headers),
        "## How to read rows",
        "Each cell is stored on its own. Read a row with "
        f"`knowledge_feed_get(name, locator)` (the locator looks like `row:2`) or filter "
        f"rows with `knowledge_feed_query(name, where)`; this dataset is `{name}`.",
        CHANGE_LOG,
        _change_section(len(units), changes),
    ]
    earlier = _earlier_sections(previous_text)
    if earlier:
        sections.append(earlier)
    return "\n\n".join(sections) + "\n"


def _move_copies_aside(cfg: Config, repo: str, name: str,
                       moved: list[tuple[Path, Path]]) -> None:
    """Rename every copy of this name out of the way, whichever extension it has.

    Recorded in `moved` as each rename succeeds, so a failure halfway leaves the caller a
    partial list, which is exactly what its rollback restores from.
    """
    for suffix in ALLOWED_SUFFIXES:
        old = _copy_path(cfg, repo, name, suffix)
        if not old.exists():
            continue
        backup = Path(f"{old}.bak")
        os.replace(old, backup)
        moved.append((backup, old))


def _checked_name(name: str) -> str:
    """The dataset name as the commands accept it, or the ValueError saying why not.

    Shared by `feed` and `remove_dataset`: the name becomes a glob, a path segment and a
    frontmatter value, so one that cannot be all three safely must not be created or
    looked up at all.
    """
    reason = kinds.custom_kind_error(name)
    if reason is not None:
        raise ValueError(f"invalid dataset name {name!r}: {reason}")
    if name in LITERAL_NAMES:
        raise ValueError(
            f"invalid dataset name {name!r}: frontmatter would read it as a JSON literal")
    return name


def feed(conn: sqlite3.Connection, cfg: Config, path: Path, name: str,
         settings: FeedSettings | None = None, repo: str | None = None) -> FeedResult:
    """Copy a table export into the knowledge base and make its cells searchable.

    Order matters for crash safety: everything that can refuse the file happens before a
    byte is written, the copy and the document are written outside the transaction (a file
    cannot be rolled back), and the unit rows, the document row and its chunks land in one
    transaction whose failure restores every file it touched.
    """
    path = Path(path)
    _checked_name(name)
    handle = _lock(cfg, name)
    try:
        return _feed_locked(conn, cfg, path, name, settings, repo)
    finally:
        _unlock(handle)


def _feed_locked(conn: sqlite3.Connection, cfg: Config, path: Path, name: str,
                 settings: FeedSettings | None, repo: str | None) -> FeedResult:
    if not path.is_file():
        # With errno and filename set, the MCP boundary can tell this vanished export apart
        # from a missing copy or staging file, which carries paths and stays infrastructure.
        raise FileNotFoundError(errno.ENOENT, "does not exist", str(path))
    suffix = path.suffix.lower()
    if suffix not in ALLOWED_SUFFIXES:
        raise ValueError(
            f"unsupported file type '{suffix}'; accepted: {', '.join(ALLOWED_SUFFIXES)}")
    if is_denied(path, cfg):
        raise PermissionError(f"{path} is on the deny list and is never fed")
    # One read: the sha the document records must describe the bytes that were copied.
    data = path.read_bytes()
    warnings: list[str] = []
    if len(data) > LARGE_FILE_BYTES:
        warnings.append(f"{path.name} is {len(data) / (1024 * 1024):.0f} MB; feeding anyway")
    resolved_repo = _resolve_repo(cfg, repo)
    doc_path = _dataset_doc_path(cfg, resolved_repo, name)
    existing = _dataset_doc(cfg, name)
    previous_text = existing.read_text() if existing is not None else None
    previous_meta = markdown.parse_frontmatter(previous_text)[0] if previous_text else {}
    if existing is not None:
        owner = previous_meta.get("repo") or existing.parent.parent.name
        if owner != resolved_repo:
            raise ValueError(
                f"'{name}' is fed under repo {owner}; use another name or "
                f"`akasha feed rm {name}` first")
    if settings is None:
        if existing is None:
            raise ValueError(f"first feed of '{name}' needs settings (at least key)")
        settings = _settings_from(previous_meta, name)

    copy = _copy_path(cfg, resolved_repo, name, suffix)
    file_sha = hashlib.sha256(data).hexdigest()
    state = unit_state(file_sha, settings.sha256(), cfg)
    stored = feed_store.load_units(conn, name)
    indexed = conn.execute(
        "SELECT id FROM documents WHERE path = ? AND deleted_at IS NULL",
        (str(doc_path),)).fetchone()
    if (existing is not None and indexed is not None
            and feed_store.stored_state(conn, name) == state
            and copy.is_file() and hashlib.sha256(copy.read_bytes()).hexdigest() == file_sha):
        # A copy deleted behind akasha's back is not "unchanged": falling through to a
        # normal feed is the repair the fsck finding points at.
        return FeedResult(name=name, repo=resolved_repo, doc_id=indexed["id"], copy=copy,
                          units=len(stored), diff=None, unchanged=True, renamed=[],
                          warnings=warnings, redacted=0)

    staging = _staging_path(cfg, resolved_repo, name, suffix)
    backups: list[tuple[Path, Path]] = []
    stale: list[Path] = []
    failures_before = len(ATTACH_ERRORS)
    swapped = False
    doc_written = False
    try:
        staging.parent.mkdir(parents=True, exist_ok=True)
        # One snapshot: the hash above, the split below and the copy that is installed all
        # describe these bytes, even when the source changes while the feed runs.
        staging.write_bytes(data)
        split_result = splitters.split(staging, name, settings)
        warnings.extend(split_result.warnings)
        units, redacted = redact_units(split_result.units, cfg)
        changes = feed_store.diff(stored, units) if existing is not None else None
        if "dataset" not in cfg.custom_kinds:
            # Before the transaction: registering rewrites the config file and commits its
            # event, neither of which a rollback of the dataset could undo.
            knowledge._register_custom_kind(conn, cfg, "dataset")
        meta = {
            "title": f"Dataset: {name}",
            "kind": "dataset",
            "feature": name,
            "repo": resolved_repo,
            "dataset": name,
            "file": str(copy),
            "sha256": file_sha,
            "settings_sha256": settings.sha256(),
            "settings": json.loads(settings.to_json()),
        }
        text = markdown.render(
            meta, _doc_body(name, path.name, units, split_result.headers, changes,
                            previous_text))
        _move_copies_aside(cfg, resolved_repo, name, backups)
        os.replace(staging, copy)
        swapped = True
        conn.execute("BEGIN IMMEDIATE")
        feed_store.replace_units(conn, name, units, state)
        stale = _drop_removed_copy(conn, cfg, name, resolved_repo)
        doc_path.parent.mkdir(parents=True, exist_ok=True)
        doc_written = True
        doc_path.write_text(text)
        knowledge._reindex(conn, cfg, doc_path, commit=False)
        failures = [message for dataset, message in ATTACH_ERRORS[failures_before:]
                    if dataset == name]
        if failures:
            # attach records a data problem and keeps the last good units; for a feed, the
            # units it just stored are not what got attached, so it is a failed write.
            raise ValueError(failures[0])
        conn.execute("COMMIT")
    except Exception as exc:
        cleanup: list[str] = []
        if conn.in_transaction:
            try:
                conn.execute("ROLLBACK")
            except sqlite3.Error as failure:
                cleanup.append(f"could not roll back: {failure}")
        # A backup restores its own name, so unlinking the new copy is right unless one of
        # them is that name: a feed that changed the extension renamed the old copy away.
        if swapped and all(original != copy for _backup, original in backups):
            try:
                copy.unlink(missing_ok=True)
            except OSError as failure:
                cleanup.append(f"could not remove {copy}: {failure}")
        for backup, original in backups:
            try:
                os.replace(backup, original)
            except OSError as failure:
                cleanup.append(f"could not restore {original}: {failure}")
        try:
            staging.unlink(missing_ok=True)
        except OSError as failure:
            cleanup.append(f"could not remove {staging}: {failure}")
        # Only a document this call wrote is restored: rewriting one that was never touched
        # moves its mtime, and the next index run then re-reads and re-attaches it.
        if doc_written:
            try:
                if previous_text is None:
                    doc_path.unlink(missing_ok=True)
                else:
                    doc_path.write_text(previous_text)
            except OSError as failure:
                cleanup.append(f"could not restore {doc_path}: {failure}")
        # The reason the feed failed is what the caller can act on; a cleanup that failed
        # too is attached to it rather than replacing it.
        for note in cleanup:
            exc.add_note(note)
        raise

    for backup, original in backups:
        try:
            if original == copy:
                backup.unlink(missing_ok=True)
            else:
                trashed = _trash_path(cfg, resolved_repo, name, original.suffix)
                trashed.parent.mkdir(parents=True, exist_ok=True)
                os.replace(backup, trashed)
        except OSError as exc:
            # The feed has landed; a leftover backup can only be reported, not undone.
            warnings.append(f"left {backup.name} behind: {exc}")
    # Only now: a rolled-back feed keeps the tombstones these files belong to.
    for removed in stale:
        try:
            removed.unlink(missing_ok=True)
        except OSError as exc:
            warnings.append(f"left {removed.name} behind: {exc}")
    try:
        vectors.index_chunks(conn, cfg)
    except Exception as exc:                                     # noqa: BLE001
        warnings.append(f"vectors not updated: {exc}")

    row = conn.execute("SELECT id FROM documents WHERE path = ?",
                       (str(doc_path),)).fetchone()
    return FeedResult(name=name, repo=resolved_repo, doc_id=row["id"], copy=copy,
                      units=len(units), diff=changes, unchanged=False,
                      renamed=split_result.renamed, warnings=warnings, redacted=redacted)


def _field_names(units: list[Unit]) -> list[str]:
    return sorted({field for unit in units for field in unit.fields})


def _dataset_units(conn: sqlite3.Connection, name: str) -> list[Unit]:
    """The stored units, or the KeyError for a name nothing was ever fed under.

    No units only means the dataset is empty when a stored state says it was fed; with
    neither, the caller named a dataset that does not exist."""
    units = feed_store.load_units(conn, name)
    if not units and feed_store.stored_state(conn, name) is None:
        raise KeyError(f"no dataset '{name}'")
    return units


def get_unit(conn: sqlite3.Connection, name: str, locator: str) -> Unit:
    """One stored row, addressed as `row:N` or `key:V`.

    A locator copied out of a search hit has to read back what the feed stored, so this
    reads the unit row itself; the chunk text renders the cell and is not the truth.
    """
    column, value = ("key", locator[len("key:"):]) if locator.startswith("key:") else (
        "locator", locator)
    row = conn.execute(
        "SELECT locator, key, label, fields FROM feed_units"
        f" WHERE dataset = ? AND {column} = ?", (name, value)).fetchone()
    if row is None:
        _dataset_units(conn, name)      # an unknown dataset outranks an unknown locator
        raise KeyError(f"no unit {locator} in '{name}'")
    return Unit(locator=row["locator"], key=row["key"], label=row["label"],
                fields=json.loads(row["fields"]))


def query_units(conn: sqlite3.Connection, name: str, where: list[str] | tuple = (),
                fields: list[str] | None = None, limit: int = 20) -> list[Unit]:
    """Rows whose cells match every `where` item, in stored order.

    An item is `field=value` (the whole cell equals it) or `field~value` (the cell
    contains it), split at its first operator so a value may hold one too. Both compare
    case-insensitively, because the caller's spelling is not the export's. An unknown
    dataset fails like `get_unit`: an empty result would not say which mistake was made.
    """
    units = _dataset_units(conn, name)
    known = _field_names(units)

    def checked(field: str) -> str:
        if field not in known:
            raise ValueError(f"unknown field '{field}'; fields: {', '.join(known)}")
        return field

    conditions: list[tuple[str, str, str]] = []
    for item in where:
        cuts = [at for at in (item.find("="), item.find("~")) if at >= 0]
        if not cuts:
            # Nothing tells a field from a value here, so name the fields the caller
            # could have meant instead of silently matching every row.
            raise ValueError(f"unknown field '{item}'; fields: {', '.join(known)}")
        at = min(cuts)
        conditions.append((checked(item[:at]), item[at], item[at + 1:]))

    projected = [checked(field) for field in fields] if fields is not None else None
    limit = max(1, min(100, limit))

    def matches(unit: Unit) -> bool:
        for field, operator, value in conditions:
            cell = unit.fields.get(field, "").casefold()
            if (cell != value.casefold() if operator == "="
                    else value.casefold() not in cell):
                return False
        return True

    found: list[Unit] = []
    for unit in units:
        if not matches(unit):
            continue
        if projected is not None:
            unit = unit._replace(fields={field: unit.fields[field] for field in projected
                                         if field in unit.fields})
        found.append(unit)
        if len(found) == limit:
            break
    return found


def remove_dataset(conn: sqlite3.Connection, cfg: Config, name: str) -> tuple[Path, Path]:
    """Take a dataset out of the knowledge base, keeping its document and copy in trash.

    Returns where each went. The copy leaves first, so a failure before the database part
    can put it straight back; the unit rows, the cell mapping and the document's tombstone
    then land in one transaction. `knowledge.restore` and `feed` are what put a name back.
    """
    _checked_name(name)
    handle = _lock(cfg, name)
    try:
        doc = _dataset_doc(cfg, name)
        row = None if doc is None else conn.execute(
            "SELECT id FROM documents WHERE path = ?", (str(doc),)).fetchone()
        if row is None:
            raise KeyError(f"no dataset '{name}'")
        repo = doc.parent.parent.name
        doc_trash = knowledge._doc_trash_path(cfg, row["id"], doc)
        moved: list[tuple[Path, Path]] = []
        for suffix in ALLOWED_SUFFIXES:
            old = _copy_path(cfg, repo, name, suffix)
            if not old.exists():
                continue
            trashed = _trash_path(cfg, repo, name, suffix)
            trashed.parent.mkdir(parents=True, exist_ok=True)
            os.replace(old, trashed)
            moved.append((trashed, old))
        # A copy deleted behind akasha's back is what fsck reports as `missing_copy`, and
        # this is the command that clears it, so a missing copy must not crash either.
        copy_trash = moved[-1][0] if moved else _trash_path(cfg, repo, name,
                                                            ALLOWED_SUFFIXES[0])
        try:
            conn.execute("BEGIN IMMEDIATE")
            feed_store.drop_dataset(conn, name)
            doc_trash = knowledge._remove_unchecked(conn, cfg, row["id"])
            conn.execute("COMMIT")
        except Exception as exc:                                     # noqa: BLE001
            if conn.in_transaction:
                try:
                    conn.execute("ROLLBACK")
                except sqlite3.Error as failure:
                    exc.add_note(f"could not roll back: {failure}")
            for trashed, old in moved:
                os.replace(trashed, old)
            # `remove` moves the document before it writes, so a failure here has to put
            # that back too: a live row beside a document in the trash is torn.
            if not doc.exists() and doc_trash.exists():
                os.replace(doc_trash, doc)
            raise
        return doc_trash, copy_trash
    finally:
        _unlock(handle)


def _drop_removed_copy(conn: sqlite3.Connection, cfg: Config, name: str,
                       repo: str) -> list[Path]:
    """Forget the tombstone a removed dataset of this name left behind.

    `index_path` derives a document id from its path, and a tombstone still holds the id
    of the path this feed is about to create again, so leaving it in place collides with
    its own trash. Returns the trashed files the caller unlinks once it has committed:
    left behind they are files no row points at, which `purge` can never reach.

    A tombstone is this dataset's only when its id is the one the live path derives: a
    removed note can be moved to the same trash file name and carry the same frontmatter,
    and dropping that one would delete a document the user can still restore.
    """
    own_path = _dataset_doc_path(cfg, repo, name)
    trash = cfg.knowledge_dir.parent / "trash"
    stale: list[Path] = []
    for row in conn.execute(
            "SELECT id, path, repo, source FROM documents"
            " WHERE deleted_at IS NOT NULL").fetchall():
        own_id = knowledge._expected_id(conn, cfg, own_path, source=row["source"])
        if row["id"] != own_id:
            continue
        path = Path(row["path"])
        if path.parent != trash or path.name != f"{own_id}__{name}.md":
            continue
        if not path.is_file():          # a row whose file is gone is still a tombstone
            continue
        meta, _body = markdown.parse_frontmatter(path.read_text(errors="replace"))
        if knowledge._trashed_dataset(conn, row, meta, cfg) != name:
            continue
        if (meta.get("repo") or "_global") != repo:
            continue
        conn.execute("DELETE FROM chunks WHERE document_id = ?", (row["id"],))
        conn.execute("DELETE FROM links WHERE from_document_id = ? OR to_document_id = ?",
                     (row["id"], row["id"]))
        conn.execute("DELETE FROM documents WHERE id = ?", (row["id"],))
        stale.append(Path(row["path"]))
    return stale
